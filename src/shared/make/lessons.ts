/**
 * system に足す決まり（--draw-extra のファイルの中身）を足す。system にもう同じ行（「- 」で始まる決まりの行）があるときと、
 * 教訓で置き換えた古い行（SUPERSEDED）は省く。決まりの行が 1 つも残らなければ、見出しも足さず system をそのまま返す
 */
export function addDrawExtra(system: string, extra: string): string {
  const have = new Set(system.split("\n").map((l) => l.trim()).filter((l) => l.startsWith("- ")));
  for (const l of SUPERSEDED) have.add(l);
  const kept = extra
    .trim()
    .split("\n")
    .filter((l) => !have.has(l.trim()));
  if (!kept.some((l) => l.trim().startsWith("- "))) return system;
  return `${system}\n${kept.join("\n")}`;
}
